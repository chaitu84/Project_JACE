"""Prepare and validate one real candidate; optionally run/inspect IntaRNA.

Run from the repository root. Original search outputs are read-only.
IntaRNA sequence 1 (target) is human; sequence 2 (query) is viral.
"""

import argparse
import csv
import gzip
import hashlib
import json
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys

from Bio import SeqIO

# Reuse the exact matching and RNA-normalization functions from Step 3.
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "complements"))
from complementary import WINDOW_SIZE, find_matches, read_fasta, rev_comp


ROOT = Path(__file__).resolve().parents[3]
MATCHES = ROOT / "results/exact_complementarity_matches.csv"
VIRUS = ROOT / "src/config_code/hpv_step2/targets/HPV16_E6starI_E7_spliced_region.rna.fasta"
DEFAULT_ID = "ENST00000832824.1"
CSV_COLUMNS = "id1,start1,end1,id2,start2,end2,subseq1,subseq2,hybridDP,bpList,E,E_hybrid,ED1,ED2"


def require(condition, message):
    """Use explicit checks so validation also runs under Python -O."""
    if not condition:
        raise ValueError(message)


def get_candidate_rows(transcript_id):
    require(MATCHES.is_file(), f"Missing real-match CSV: {MATCHES}")
    with MATCHES.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        fields = reader.fieldnames
        rows = list(reader)
    require(bool(rows), "The real-match CSV has no candidate rows.")
    selected = [row for row in rows if row["hum_trspt_id"] == transcript_id]
    reason = "Requested demonstration candidate; no strength ranking was performed."
    if not selected:
        # Deterministic fallback: first real match, never a shuffled match.
        transcript_id = rows[0]["hum_trspt_id"]
        selected = [row for row in rows if row["hum_trspt_id"] == transcript_id]
        reason = "Requested ID absent; selected the first transcript in the real-match CSV."
    return transcript_id, selected, fields, reason


def get_human_sequence(fasta, transcript_id):
    require(fasta.is_file(), f"Missing GENCODE lncRNA FASTA: {fasta}")
    opener = gzip.open if fasta.suffix.lower() == ".gz" else open
    found = []
    with opener(fasta, "rt", encoding="utf-8") as handle:
        for record in SeqIO.parse(handle, "fasta"):
            # GENCODE record.id includes pipe-separated gene/name/length fields.
            if record.id.split("|")[0] == transcript_id:
                found.append(record)
    require(len(found) == 1, f"Expected one FASTA record for {transcript_id}; found {len(found)}")
    record = found[0]
    original = str(record.seq).upper()
    return record.description, original, original.replace("T", "U")


def validate_matches(rows, human, viral_id, viral):
    """Check every recorded field and independently enumerate this candidate's hits."""
    observed = []
    for number, row in enumerate(rows, 1):
        hs, he, vs, ve = (int(row[key]) for key in
                          ("human_start", "human_end", "viral_start", "viral_end"))
        require(0 <= hs < he <= len(human), f"Row {number}: human bounds")
        require(0 <= vs < ve <= len(viral), f"Row {number}: viral bounds")
        require(he - hs == ve - vs == WINDOW_SIZE, f"Row {number}: window length")
        chunk, matched = viral[vs:ve], human[hs:he]
        require(row["viral_rna_id"] == viral_id, f"Row {number}: viral ID")
        require(chunk == row["viral_window"], f"Row {number}: viral slice")
        require(rev_comp(chunk) == row["viral_reverse_complement"] ==
                row["human_matched_sequence"] == matched, f"Row {number}: reverse complement")
        require([int(row[key]) for key in ("matches", "match_length", "mismatches", "gaps")]
                == [WINDOW_SIZE, WINDOW_SIZE, 0, 0], f"Row {number}: match statistics")
        observed.append((hs, he, vs, ve))
    expected = []
    for vs in range(len(viral) - WINDOW_SIZE + 1):
        chunk = viral[vs:vs + WINDOW_SIZE]
        if set(chunk) <= set("ACGU"):
            for hs in find_matches(rev_comp(chunk), human):
                expected.append((hs, hs + WINDOW_SIZE, vs, vs + WINDOW_SIZE))
    require(sorted(expected) == sorted(observed), "Candidate CSV differs from a fresh exact search")


def inspect_prediction(path, rows, human_id, human, viral_id, viral):
    """Convert IntaRNA 1-based inclusive spans and test overlap on BOTH RNAs.

    Span overlap is not proof that the original 10 base pairs are predicted.
    This accepts the CSV generated by the documented command below.
    """
    with path.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle, delimiter=";")
        require(set(CSV_COLUMNS.split(",")) <= set(reader.fieldnames or []),
                "Prediction CSV is missing required headers; use the documented output columns")
        predictions = list(reader)
    result = []
    for prediction in predictions:
        require(prediction["id1"] == human_id and prediction["id2"] == viral_id,
                "Prediction must use human as target/sequence 1 and virus as query/sequence 2")
        hs, he = int(prediction["start1"]) - 1, int(prediction["end1"])
        vs, ve = int(prediction["start2"]) - 1, int(prediction["end2"])
        require(0 <= hs < he <= len(human) and 0 <= vs < ve <= len(viral),
                "Prediction coordinates outside full input sequences")
        require(prediction["subseq1"].upper().replace("T", "U") == human[hs:he],
                "Prediction human subsequence does not match input")
        require(prediction["subseq2"].upper().replace("T", "U") == viral[vs:ve],
                "Prediction viral subsequence does not match input")
        pairs = {(int(h), int(v)) for h, v in
                 re.findall(r"\((\d+),(\d+)\)", prediction["bpList"])}
        require(bool(pairs), "Prediction has no readable bpList base pairs")
        for h, v in pairs:
            require(hs < h <= he and vs < v <= ve, "Base pair outside predicted spans")
            require(human[h - 1] + viral[v - 1] in {"AU", "UA", "GC", "CG", "GU", "UG"},
                    "Predicted base pair disagrees with input sequences")
        overlaps = []
        for number, row in enumerate(rows, 1):
            human_overlap = max(0, min(he, int(row["human_end"])) - max(hs, int(row["human_start"])))
            viral_overlap = max(0, min(ve, int(row["viral_end"])) - max(vs, int(row["viral_start"])))
            # Antiparallel pairing: first human base pairs with last viral base.
            original_pairs = {(int(row["human_start"]) + i + 1, int(row["viral_end"]) - i)
                              for i in range(WINDOW_SIZE)}
            shared_pairs = len(pairs & original_pairs)
            overlaps.append({"original_row": number, "human_overlap_nt": human_overlap,
                             "viral_overlap_nt": viral_overlap,
                             "overlaps_both_spans": human_overlap > 0 and viral_overlap > 0,
                             "original_base_pairs_predicted": shared_pairs,
                             "complete_original_10mer_pairing": shared_pairs == WINDOW_SIZE})
        result.append({"human_interval_0based_half_open": [hs, he],
                       "viral_interval_0based_half_open": [vs, ve],
                       "original_match_overlap": overlaps,
                       "interpretation": "Span overlap and exact original base-pair overlap are reported separately."})
    return {"prediction_rows": len(predictions), "interactions": result}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--transcript", default=DEFAULT_ID)
    default_fasta = ROOT / "data/gencode.v50.lncRNA_transcripts.fa.gz"
    if not default_fasta.exists():
        default_fasta = ROOT / "data/gencode.v50.lncRNA_transcripts.fa"
    parser.add_argument("--human-fasta", type=Path, default=default_fasta)
    parser.add_argument("--out-dir", type=Path, default=ROOT / "results/step5/worked_example")
    parser.add_argument("--run-intarna", action="store_true")
    parser.add_argument("--intarna", default="IntaRNA", help="Executable name or full path")
    parser.add_argument("--prediction", type=Path, help="Inspect an existing IntaRNA semicolon CSV")
    args = parser.parse_args()

    transcript_id, rows, fields, reason = get_candidate_rows(args.transcript)
    header, original, human = get_human_sequence(args.human_fasta, transcript_id)
    require(VIRUS.is_file(), f"Missing original spliced viral-target FASTA: {VIRUS}")
    viral_id, viral = read_fasta(VIRUS)
    require(bool(human) and set(human) <= set("ACGU"), "Human sequence must be unambiguous RNA")
    require(bool(viral) and set(viral) <= set("ACGU"), "Viral sequence must be unambiguous RNA")
    validate_matches(rows, human, viral_id, viral)

    out = args.out_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    human_path = out / f"{transcript_id}.full.rna.fasta"
    viral_path = out / "HPV16_E6starI_E7_spliced_region.original.rna.fasta"
    with human_path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(f">{transcript_id} GENCODE_v50 full_transcript length={len(human)} orientation=5to3\n")
        for start in range(0, len(human), 70):
            handle.write(human[start:start + 70] + "\n")
    shutil.copyfile(VIRUS, viral_path)  # Preserve original viral header, sequence and bytes.
    with (out / "candidate_real_matches.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)

    prediction_path = out / "intarna_prediction.csv"
    # Full sequences; local folding with documented W=150/L=100 server settings.
    # The seed is NOT forced to an original exact 10-mer match.
    command = [args.intarna, f"--target={human_path}", f"--query={viral_path}",
               "--model=X", "--mode=H", "--acc=C", "--tAccW=150", "--tAccL=100",
               "--qAccW=150", "--qAccL=100", "--seedBP=7", "--outNumber=1",
               "--outMode=C", f"--outCsvCols={CSV_COLUMNS}", f"--out={prediction_path}"]
    # Paths are relative to this output folder so this command is portable to WSL/Linux.
    portable = ["IntaRNA", f"--target={human_path.name}", f"--query={viral_path.name}",
                *command[3:-1], "--out=intarna_prediction.csv"]
    (out / "intarna_command.txt").write_text(shlex.join(portable) + "\n", encoding="utf-8")
    report = {
        "transcript_id": transcript_id, "selection_reason": reason,
        "gencode_header": header, "human_source": str(args.human_fasta.resolve()),
        "real_match_source": str(MATCHES), "viral_source": str(VIRUS),
        "human_length_nt": len(human), "viral_length_nt": len(viral),
        "orientation": "Both original 5-prime to 3-prime; neither reverse-complemented",
        "normalization": "Human uppercase T replaced by U; original viral RNA copied unchanged",
        "human_T_to_U_count": original.count("T"), "validated_match_rows": len(rows),
        "candidate_fresh_search_matches_csv": True,
        "human_rna_sha256": hashlib.sha256(human.encode("ascii")).hexdigest(),
        "viral_rna_sha256": hashlib.sha256(viral.encode("ascii")).hexdigest(),
        "coordinates": "Original CSV is 0-based half-open; IntaRNA is 1-based inclusive",
        "full_sequence_mapping": "IntaRNA [start,end] -> full Python [start-1:end]; no crop offset",
        "intarna_arguments": command,
        "prediction_status": "Not run by this invocation", "overlap_status": "Pending actual prediction",
    }
    if args.run_intarna:
        executable = shutil.which(args.intarna)
        if executable is None:
            report["prediction_status"] = f"Executable unavailable: {args.intarna}; use intarna_command.txt or official web GUI"
        else:
            version = subprocess.run([executable, "--version"], capture_output=True, text=True, check=False)
            (out / "intarna_version.txt").write_text(version.stdout + version.stderr, encoding="utf-8")
            # Avoid reading an old output as if it came from a failed new run.
            require(not prediction_path.exists(), f"Prediction already exists: {prediction_path}; inspect it with --prediction")
            run = subprocess.run(command, capture_output=True, text=True, check=False)
            (out / "intarna_stdout.txt").write_text(run.stdout, encoding="utf-8")
            (out / "intarna_stderr.txt").write_text(run.stderr, encoding="utf-8")
            report["prediction_return_code"] = run.returncode
            report["prediction_status"] = "Succeeded" if run.returncode == 0 else "Failed; see intarna_stderr.txt"
            if run.returncode == 0:
                require(prediction_path.is_file(), "IntaRNA returned success without the requested CSV")
                args.prediction = prediction_path
    if args.prediction:
        report["prediction_inspected"] = str(args.prediction.resolve())
        overlap = inspect_prediction(args.prediction, rows, transcript_id, human, viral_id, viral)
        (out / "prediction_overlap.json").write_text(json.dumps(overlap, indent=2) + "\n", encoding="utf-8")
        report["overlap_status"] = f"Checked {overlap['prediction_rows']} prediction rows; see prediction_overlap.json"
    (out / "candidate_validation.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(f"Validated {len(rows)} exact matches: {transcript_id} ({len(human)} nt), virus ({len(viral)} nt)")
    print(f"Saved inputs and validation: {out}")
    print(report["prediction_status"])
    print(report["overlap_status"])
    if report.get("prediction_return_code", 0) != 0:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
